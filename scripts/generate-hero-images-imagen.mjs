#!/usr/bin/env node
/**
 * Generate Market Reality hero images using Gemini Imagen (Nano Banana / image generation).
 * Requires: GEMINI_API_KEY in .env
 * Run: npm run generate-hero-images
 *
 * Uses prompts derived from slide content. Saves to public/images/marketReality/ and
 * updates src/data/marketRealityImages.js to use local paths.
 */
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const projectRoot = path.resolve(__dirname, '..')

async function loadEnv() {
  try {
    const dotenv = await import('dotenv')
    dotenv.config({ path: path.join(projectRoot, '.env') })
  } catch (_) {}
}

const HERO_PROMPTS = {
  slide1:
    'Professional, dark mood. Abstract visual suggesting crisis of trust and disruption: subtle tension, then clarity. Modern minimalist style, no pill bottles or literal supplements. Dark blue-grey tones, suitable for a startup pitch deck. High quality, 16:9 aspect.',
  slide2:
    'Two diverse professionals in a wellness context, soft natural light. Warm, approachable mood. Suggests "our people" and target audience. Modern, clean, professional. No text or logos. 16:9 aspect.',
  slide3:
    'Clean, data-driven aesthetic. E-commerce and digital growth: laptop or device with charts, modern SaaS vibe. Professional startup style. Bright, minimal. No text or logos. 16:9 aspect.',
  slide4:
    'Premium, trustworthy mood. Two paths or options visualized in an abstract way: one side modern and convenient, one side clinical and authoritative. Sophisticated, professional. Dark or neutral tones. 16:9 aspect.',
}

async function generateWithImagen(ai, slideKey, prompt) {
  const model = 'imagen-4.0-generate-001'
  console.log(`  Generating ${slideKey} with ${model}...`)
  const response = await ai.models.generateImages({
    model,
    prompt,
    config: { numberOfImages: 1 },
  })
  const img = response?.generatedImages?.[0]?.image
  if (!img?.imageBytes) throw new Error(`No image in response for ${slideKey}`)
  return Buffer.from(img.imageBytes, 'base64')
}

function writeMarketRealityImagesJs() {
  const content = `/**
 * Image paths for Market Reality 4-slide deck.
 * Generated by npm run generate-hero-images (Imagen). To use placeholders again, see git history.
 */
export const marketRealityImages = {
  slide1: { hero: '/images/marketReality/slide1-hero.png', inline: null },
  slide2: { hero: '/images/marketReality/slide2-hero.png', inline: null },
  slide3: { hero: '/images/marketReality/slide3-hero.png', inline: null },
  slide4: { hero: '/images/marketReality/slide4-hero.png', inline: null },
}
`
  const outPath = path.join(projectRoot, 'src', 'data', 'marketRealityImages.js')
  fs.writeFileSync(outPath, content, 'utf8')
  console.log('Updated', outPath)
}

async function main() {
  await loadEnv()
  const apiKey = process.env.GEMINI_API_KEY
  if (!apiKey) {
    console.error('GEMINI_API_KEY is required. Add it to .env (get a key from Google AI Studio).')
    process.exit(1)
  }

  const { GoogleGenAI } = await import('@google/genai')
  const ai = new GoogleGenAI({ apiKey })

  const outDir = path.join(projectRoot, 'public', 'images', 'marketReality')
  fs.mkdirSync(outDir, { recursive: true })

  let successCount = 0
  for (const [slideKey, prompt] of Object.entries(HERO_PROMPTS)) {
    try {
      const buffer = await generateWithImagen(ai, slideKey, prompt)
      const filename = `${slideKey}-hero.png`
      const filePath = path.join(outDir, filename)
      fs.writeFileSync(filePath, buffer)
      console.log('  Wrote', filePath)
      successCount++
    } catch (e) {
      console.error(`  Failed ${slideKey}:`, e.message)
      if (e.message?.includes('paid') || e.message?.includes('400')) {
        console.error('  Imagen requires a paid Gemini plan. See https://ai.google.dev/gemini-api/docs/imagen')
      }
    }
  }

  if (successCount > 0) {
    writeMarketRealityImagesJs()
    console.log('Done. Refresh the Market Reality tab to see the new hero images.')
  } else {
    console.log('No images were generated. marketRealityImages.js was not changed. Use placeholders or add images to public/images/marketReality/ manually.')
  }
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})
